// Render text using the pixel font. Caller must set g.fillStyle before calling.
export function print(g: Phaser.GameObjects.Graphics, text: string, x: number, y: number, px = 2) {
  let cx = x
  for (const ch of text.toUpperCase()) {
    const bm = FONT[ch] ?? FONT[' ']
    for (let r = 0; r < bm.length; r++)
      for (let c = 0; c < bm[r].length; c++)
        if (bm[r][c]) g.fillRect(cx + c * px, y + r * px, px, px)
    cx += (bm[0]?.length ?? 3) * px + px
  }
}

// Measure text width in pixels at given scale.
export function textW(text: string, px = 2): number {
  let w = 0
  for (const ch of text.toUpperCase()) {
    const bm = FONT[ch] ?? FONT[' ']
    w += (bm[0]?.length ?? 3) * px + px
  }
  return w
}
